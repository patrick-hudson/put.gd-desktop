#!/usr/bin/env python3
"""Deterministic public release bundle; exact positive inventory, standard library."""
import datetime
import hashlib
import json
import os
from pathlib import Path
import re
import stat
import zipfile

from release_identity import parse_version


def expected_members(version):
    parse_version(version)
    return [
        'putgd-' + version + '-ubuntu24.04-x86_64.deb',
        'putgd-' + version + '-ubuntu26.04-x86_64.deb',
        'putgd-' + version + '-debian13-x86_64.deb',
        'putgd-' + version + '-fedora44-x86_64.rpm',
        'putgd-' + version + '-x86_64.AppImage',
        'putgd-' + version + '-x86_64.AppImage.zsync',
        'putgd-' + version + '-appimage-media-source.tar.gz',
        'putgd-' + version + '-source.tar.gz',
        'putgd-gnome50-' + version + '.zip', 'release-builds.json', 'proton-source-catalog.json',
    ]


def _safe_name(name):
    if (not isinstance(name, str) or name in ('.', '..', 'credentials.txt', '.env')
            or name.startswith('.env.') or not re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9._+-]*', name)):
        raise ValueError('unsafe ZIP member filename')


def _zip_time(timestamp):
    if type(timestamp) is not int or timestamp < 0:
        raise ValueError('integer release commit timestamp required')
    try:
        utc = datetime.datetime.fromtimestamp(timestamp, datetime.timezone.utc)
    except (ValueError, OSError, OverflowError) as error:
        raise ValueError('unsupported ZIP timestamp') from error
    low = datetime.datetime(1980, 1, 1, tzinfo=datetime.timezone.utc)
    high = datetime.datetime(2107, 12, 31, 23, 59, 58, tzinfo=datetime.timezone.utc)
    utc = min(max(utc, low), high)
    return (utc.year, utc.month, utc.day, utc.hour, utc.minute, utc.second // 2 * 2)


def _regular(path):
    path = Path(path)
    before = path.lstat()
    if not stat.S_ISREG(before.st_mode):
        raise ValueError('ZIP input is missing, symlink, or unsupported entry')
    fd = os.open(path, os.O_RDONLY | getattr(os, 'O_NOFOLLOW', 0))
    actual = os.fstat(fd)
    if not stat.S_ISREG(actual.st_mode) or (actual.st_dev, actual.st_ino) != (before.st_dev, before.st_ino):
        os.close(fd)
        raise ValueError('ZIP input identity changed')
    return os.fdopen(fd, 'rb'), actual


def _fingerprint(value):
    return value.st_dev, value.st_ino, value.st_size, value.st_mtime_ns


def _hash_source(source):
    if isinstance(source, bytes):
        return len(source), hashlib.sha256(source).hexdigest()
    stream, before = _regular(source)
    digest = hashlib.sha256()
    size = 0
    with stream:
        for chunk in iter(lambda: stream.read(1048576), b''):
            size += len(chunk)
            digest.update(chunk)
        after = os.fstat(stream.fileno())
    if size != before.st_size or _fingerprint(before) != _fingerprint(after):
        raise ValueError('ZIP input changed while hashing')
    return size, digest.hexdigest()


def _write_zip(entries, output_file, timestamp):
    """entries maps flat names to (regular Path or generated bytes, fixed mode)."""
    output_file = Path(output_file)
    if output_file.exists() or output_file.is_symlink() or output_file.name in entries:
        raise ValueError('ZIP output already exists or collides with an input')
    when = _zip_time(timestamp)
    metadata = []
    for name, (source, mode) in sorted(entries.items()):
        _safe_name(name)
        if mode not in (0o644, 0o755):
            raise ValueError('unsupported ZIP member mode')
        size, digest = _hash_source(source)
        metadata.append({'path': name, 'bytes': size, 'sha256': digest, 'mode': f'{mode:04o}'})
    expected = {m['path']: m for m in metadata}
    try:
        target = output_file.open('xb')
    except FileExistsError as error:
        raise ValueError('ZIP output already exists') from error
    try:
        with target, zipfile.ZipFile(target, 'w', compression=zipfile.ZIP_STORED, allowZip64=True) as archive:
            archive.comment = b''
            for name, (source, mode) in sorted(entries.items()):
                info = zipfile.ZipInfo(name, when)
                info.create_system = 3
                info.compress_type = zipfile.ZIP_STORED
                info.external_attr = (stat.S_IFREG | mode) << 16
                info.file_size = expected[name]['bytes']
                info.extra = info.comment = b''
                if isinstance(source, bytes):
                    archive.writestr(info, source)
                    continue
                stream, before = _regular(source)
                digest = hashlib.sha256()
                size = 0
                with stream, archive.open(info, 'w', force_zip64=info.file_size > zipfile.ZIP64_LIMIT) as member:
                    for chunk in iter(lambda: stream.read(1048576), b''):
                        size += len(chunk)
                        digest.update(chunk)
                        member.write(chunk)
                    after = os.fstat(stream.fileno())
                if (_fingerprint(before) != _fingerprint(after) or size != expected[name]['bytes']
                        or digest.hexdigest() != expected[name]['sha256']):
                    raise ValueError('ZIP input bytes changed before completion')
        # Inspect actual archive bytes; receipt covers every member, including the
        # generated inner SHA256SUMS. Hash checks do not assert installer behavior.
        try:
            with zipfile.ZipFile(output_file) as archive:
                if archive.namelist() != sorted(entries):
                    raise ValueError('ZIP inventory/CRC verification failed')
                for item in metadata:
                    digest = hashlib.sha256()
                    size = 0
                    with archive.open(item['path']) as stream:
                        for chunk in iter(lambda: stream.read(1048576), b''):
                            size += len(chunk)
                            digest.update(chunk)
                    if size != item['bytes'] or digest.hexdigest() != item['sha256']:
                        raise ValueError('ZIP member byte verification failed')
        except zipfile.BadZipFile as error:
            raise ValueError('ZIP inventory/CRC verification failed') from error
    except Exception:
        output_file.unlink(missing_ok=True)
        raise
    size, digest = _hash_source(output_file)
    return {'schemaVersion': 1, 'format': 'ZIP', 'timestamp': timestamp, 'zipTimestampUtc': list(when),
            'artifact': {'file': output_file.name, 'bytes': size, 'sha256': digest},
            'members': metadata, 'compression': 'stored',
            'scope': 'byte-verified archive; no installation or desktop acceptance claim'}


def create_gnome_zip(root, output_file, timestamp):
    """Only the three integration files from the caller's verified clean checkout."""
    root = Path(root)
    return _write_zip({'extension.js': (root / 'integrations/gnome/extension.js', 0o644),
        'metadata.json': (root / 'integrations/gnome/metadata.json', 0o644),
        'LICENSE': (root / 'LICENSE', 0o644)}, output_file, timestamp)


def create_release_bundle(directory, output_file, version, timestamp, member_names):
    """Additional public ZIP; raw installers/source assets remain independently public."""
    directory, output_file = Path(directory), Path(output_file)
    if not stat.S_ISDIR(directory.lstat().st_mode):
        raise ValueError('ZIP input directory is missing or symlinked')
    if not isinstance(member_names, (list, tuple)) or any(not isinstance(n, str) for n in member_names):
        raise ValueError('explicit exact release member inventory required')
    if len(member_names) != len(set(member_names)):
        raise ValueError('duplicate release ZIP member')
    if set(member_names) != set(expected_members(version)):
        raise ValueError('unexpected/missing release ZIP member')
    if (output_file.parent.resolve() != directory.resolve()
            or output_file.name != 'putgd-' + version + '-release.zip'):
        raise ValueError('unsupported release ZIP output collision/location')
    entries = {name: (directory / name, 0o755 if name.endswith('.AppImage') else 0o644)
               for name in member_names}
    # Validate all regular inputs before reading the JSON manifest or creating output.
    hashes = {}
    for name, (path, _) in sorted(entries.items()):
        _safe_name(name)
        size, digest = _hash_source(path)
        hashes[name] = {'bytes': size, 'sha256': digest}
    stream, _ = _regular(directory / 'release-builds.json')
    with stream:
        builds = json.load(stream)
    if builds.get('release', {}).get('version') != version:
        raise ValueError('release-builds identity differs from ZIP version')
    checksums = ''.join(hashes[name]['sha256'] + '  ' + name + '\n' for name in sorted(hashes)).encode('ascii')
    entries['SHA256SUMS'] = (checksums, 0o644)
    result = _write_zip(entries, output_file, timestamp)
    # Ensure the inner checksums refer to exactly the bytes actually stored, even
    # if a caller changed an input between the pre-hash and the archive write.
    actual = {m['path']: m for m in result['members']}
    if any(actual[name]['sha256'] != digest['sha256'] or actual[name]['bytes'] != digest['bytes']
           for name, digest in hashes.items()):
        output_file.unlink()
        raise ValueError('inner ZIP checksums differ from archived inputs')
    result['version'] = version
    result['channel'] = parse_version(version).channel
    result['innerChecksumScope'] = 'eight underlying files only; excludes SHA256SUMS, the combined ZIP and separately delivered source transport parts'
    return result
